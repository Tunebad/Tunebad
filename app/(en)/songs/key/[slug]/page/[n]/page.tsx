import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { KeyHubPage, keyHubMeta, PAGE_SIZE } from "@/components/songs/KeyHubPage";
import { ALL_KEYS, keyToSlug } from "@/lib/audio/harmonic";
import { countSongsByKey } from "@/lib/server/link-analysis";

// /songs/key/<slug>/page/<n> — pages 2+ of a key hub.
//
// These exist for crawl reach: the hub readers are newest-first with a 300-row
// cap, so without pagination the union of every hub reached only ~8% of the
// catalog and ~109,000 song pages had no internal inbound links at all. Not
// prerendered (there are ~400 of them and they change as the catalog grows) —
// dynamicParams + ISR resolves each on first request, same as /song/[slug].
// Frozen until the next deploy (see lib/server/catalog.ts): built at deploy
// time, never regenerated by traffic, so crawlers can't cost ISR writes.
export const revalidate = false;
export const dynamicParams = false;

// Exactly the pages that have songs on them, from the same counts the hub uses
// for its own pagination links — so with dynamicParams = false a crawler
// guessing /page/9999 gets a static 404 instead of a render and an ISR write.
export async function generateStaticParams() {
  const params: { slug: string; n: string }[] = [];
  for (const key of ALL_KEYS) {
    const pages = Math.ceil((await countSongsByKey(key)) / PAGE_SIZE);
    for (let n = 2; n <= pages; n++) params.push({ slug: keyToSlug(key), n: String(n) });
  }
  return params;
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ slug: string; n: string }>;
}): Promise<Metadata> {
  const { slug, n } = await params;
  const page = Number(n);
  const meta = Number.isInteger(page) && page > 1 ? keyHubMeta(slug, page) : null;
  if (!meta) return { title: "Not found | TuneBad", robots: { index: false, follow: true } };
  return {
    title: meta.title,
    description: meta.description,
    alternates: { canonical: meta.canonical },
    openGraph: { url: meta.canonical, title: meta.title },
  };
}

export default async function Page({ params }: { params: Promise<{ slug: string; n: string }> }) {
  const { slug, n } = await params;
  const page = Number(n);
  // Page 1 has its own canonical URL (/songs/key/<slug>) — don't serve it here
  // too, and don't accept junk like /page/0 or /page/abc.
  if (!Number.isInteger(page) || page < 2) notFound();
  return <KeyHubPage slug={slug} page={page} />;
}
